"use client";
import { useEffect } from "react";
import Lenis from "lenis";

export default function SmoothScroll({ children }: { children: React.ReactNode }) {
  useEffect(() => {
    // Only enable Lenis on devices with a real pointer (desktop/trackpad).
    // Touch devices keep native scroll — smoother and more reliable there.
    const isDesktop = window.matchMedia("(pointer: fine) and (min-width: 768px)").matches;
    if (!isDesktop) return;

    const lenis = new Lenis({
      duration: 1.1,
      easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
    });

    function raf(time: number) {
      lenis.raf(time);
      requestAnimationFrame(raf);
    }
    requestAnimationFrame(raf);

    return () => lenis.destroy();
  }, []);

  return <>{children}</>;
}